const isL = /[\p{L}\p{N}]/u
let buckets: Map<string, [string, boolean, boolean][]> | null = null
function index() {
  buckets = new Map()
  for (const k of Object.keys(EN).filter((x) => x.length >= 2).sort((a, b) => b.length - a.length)) {
    const c = k.charAt(0)
    let l = buckets.get(c)
    if (!l) buckets.set(c, (l = []))
    l.push([k, isL.test(k[0] ?? ''), isL.test(k[k.length - 1] ?? '')])
  }
  return buckets
}
function partial(s: string): string {
  const by = buckets ?? index()
  let out = '', i = 0, last = 0
  while (i < s.length) {
    const list = by.get(s.charAt(i))
    let hit: string | null = null
    if (list)
      for (const [k, a, b] of list) {
        if (!s.startsWith(k, i) || (a && isL.test(s.charAt(i - 1))) || (b && isL.test(s.charAt(i + k.length)))) continue
        hit = k
        break
      }
    if (hit) {
      out += s.slice(last, i) + (EN[hit] ?? hit)
      i += hit.length
      last = i
    } else i++
  }
  return last ? out + s.slice(last) : s
}
const cache = new Map<string, string>()
/** Teksten på valgt språk. Tall, tegn og tomme verdier vises som de er. */
export function trLoop(lang: Lang, v: unknown): string {
  const s = v == null ? '' : String(v)
  if (lang !== 'en' || !s || !/[A-Za-zÆØÅæøå]/.test(s)) return s
  const hit = cache.get(s)
  if (hit !== undefined) return hit
  const lead = /^\s*/.exec(s)?.[0] ?? '', trail = /\s*$/.exec(s)?.[0] ?? '', n = s.replace(/\s+/g, ' ').trim()
  const r = EN[n] !== undefined ? lead + EN[n] + trail : partial(s)
  if (cache.size > 4000) cache.clear()
  cache.set(s, r)
  return r
}
