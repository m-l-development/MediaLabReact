export type Phrase = string

export function tr(lang: Lang, p: Phrase, v?: Vars): string {
  const s = lang === 'en' ? (EN[p] ?? p) : p
  return v ? format(s, v) : s
}

export type Tx = (p: Phrase, v?: Vars) => string

export function useTx(): Tx {
  const lang = useLang()
  return (p, v) => tr(lang, p, v)
}
